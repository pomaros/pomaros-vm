"""Generate and verify both licensed views of the AROS boot ABI."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TYPE_LAYOUT = {"uint8_t": (1, 1), "uint32_t": (4, 4), "uint64_t": (8, 8)}


def align_up(value: int, alignment: int) -> int:
    return (value + alignment - 1) & ~(alignment - 1)


def validate(schema: dict) -> None:
    if schema["version"] < 1:
        raise ValueError("ABI version must be positive")
    for structure in schema["structures"]:
        cursor = 0
        maximum_alignment = structure["alignment"]
        for field in structure["fields"]:
            item_size, item_alignment = TYPE_LAYOUT[field["type"]]
            cursor = align_up(cursor, item_alignment)
            if cursor != field["offset"]:
                raise ValueError(
                    f'{structure["name"]}.{field["name"]}: '
                    f'computed offset {cursor}, schema says {field["offset"]}'
                )
            cursor += item_size * field.get("count", 1)
            maximum_alignment = max(maximum_alignment, item_alignment)
        computed_size = align_up(cursor, maximum_alignment)
        if computed_size != structure["size"]:
            raise ValueError(
                f'{structure["name"]}: computed size {computed_size}, '
                f'schema says {structure["size"]}'
            )


def license_block(kind: str) -> list[str]:
    if kind == "mit":
        return [
            "// SPDX-License-Identifier: MIT",
            "// Copyright (c) 2026 John Knipper",
        ]
    return [
        "/*",
        " * Copyright (C) 2026 John Knipper",
        " *",
        " * Licensed under the AROS Public License (APL) Version 1.1",
        " */",
    ]


def render(schema: dict, license_kind: str) -> str:
    lines = license_block(license_kind)
    lines += [
        "// Generated by tools/gen-bootinfo.py from boot/abi/bootinfo.json.",
        "// Do not edit either generated header by hand.",
        "",
        "#ifndef AROS_APPLE_BOOTINFO_H",
        "#define AROS_APPLE_BOOTINFO_H",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        "#if defined(__cplusplus)",
        "# define AROS_BOOT_STATIC_ASSERT(condition, message) static_assert(condition, message)",
        "# define AROS_BOOT_ALIGNOF(type) alignof(type)",
        "#else",
        "# define AROS_BOOT_STATIC_ASSERT(condition, message) _Static_assert(condition, message)",
        "# define AROS_BOOT_ALIGNOF(type) _Alignof(type)",
        "#endif",
        "",
        f'#define AROS_BOOTINFO_ABI_BYTE_ORDER "{schema["byte_order"]}"',
        "",
    ]
    for constant in schema["constants"]:
        lines.append(
            f'#define {constant["name"]:<38} {constant["value"]} '
            f'/* {constant["comment"]} */'
        )
    lines.append("")

    for structure in schema["structures"]:
        lines.append(
            f'struct __attribute__((aligned({structure["alignment"]}))) '
            f'{structure["name"]} {{'
        )
        for field in structure["fields"]:
            suffix = f'[{field["count"]}]' if field.get("count") else ""
            declaration = f'    {field["type"]} {field["name"]}{suffix};'
            lines.append(f'{declaration:<48} /* {field["comment"]} */')
        lines += ["};", ""]
        lines.append(
            f'AROS_BOOT_STATIC_ASSERT(sizeof(struct {structure["name"]}) == '
            f'{structure["size"]}, "{structure["name"]} size");'
        )
        lines.append(
            f'AROS_BOOT_STATIC_ASSERT(AROS_BOOT_ALIGNOF(struct {structure["name"]}) == '
            f'{structure["alignment"]}, "{structure["name"]} alignment");'
        )
        for field in structure["fields"]:
            lines.append(
                f'AROS_BOOT_STATIC_ASSERT(offsetof(struct {structure["name"]}, '
                f'{field["name"]}) == {field["offset"]}, '
                f'"{structure["name"]}.{field["name"]} offset");'
            )
        lines.append("")

    lines += [
        "#undef AROS_BOOT_ALIGNOF",
        "#undef AROS_BOOT_STATIC_ASSERT",
        "",
        "#endif /* AROS_APPLE_BOOTINFO_H */",
        "",
    ]
    return "\n".join(lines)


def update(path: Path, expected: str, check: bool) -> bool:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == expected:
        return True
    if check:
        print(f"stale generated boot ABI header: {path}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(expected, encoding="utf-8")
    print(f"generated {path}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    parser.add_argument(
        "--schema", type=Path, default=ROOT / "boot/abi/bootinfo.json"
    )
    parser.add_argument(
        "--integration-header",
        type=Path,
        default=ROOT / "boot/arosboot/include/aros/apple/bootinfo.h",
    )
    parser.add_argument(
        "--core-root", type=Path, default=ROOT.parent / "aros-core-pomaros"
    )
    args = parser.parse_args()

    schema = json.loads(args.schema.read_text(encoding="utf-8"))
    validate(schema)
    core_header = args.core_root / "arch/aarch64-apple/include/aros/apple/bootinfo.h"
    ok = update(args.integration_header, render(schema, "mit"), args.check)
    ok = update(core_header, render(schema, "apl"), args.check) and ok
    if args.check and ok:
        print("boot ABI generated headers are current")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main())
